"use client";

import { useSyncExternalStore } from "react";
import type { Language } from "@/types/portfolio";

const languageStorageKey = "terminal-blog.language";
let storedLanguage: Language = "en";
const languageListeners = new Set<() => void>();

function readStoredLanguage(): Language {
  try {
    const value = typeof window !== "undefined" ? localStorage.getItem(languageStorageKey) : null;
    if (value === "en" || value === "ru" || value === "ko") storedLanguage = value;
  } catch {
    // Keep in-memory selection
  }
  return storedLanguage;
}

function subscribeToLanguage(listener: () => void) {
  languageListeners.add(listener);
  return () => languageListeners.delete(listener);
}

export function useStoreLanguage(): Language {
  const language = useSyncExternalStore<Language>(
    subscribeToLanguage,
    readStoredLanguage,
    () => "en"
  );
  return language;
}

